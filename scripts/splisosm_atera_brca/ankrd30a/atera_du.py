"""Prioritize Atera DU regulators for the ANKRD30A PB-defined TSS event.

This module starts from the genome-wide Atera DU result table generated by the
main workflow. It keeps the ANKRD30A regulator rows, ranks regulators by DU
association strength, and then annotates TFs with secondary ReMap 2022 binding
support around PacBio-supported TSS positions. It is used for figure labels and
for choosing the compact set of TFs shown in the DU/TCGA validation panel.
"""

from __future__ import annotations

from collections.abc import Iterable

import numpy as np
import pandas as pd

from ..config import REMAP_NR_HG38_BED
from ..probe_mapping import open_text
from ..utils import normalize_gene_symbol, project_path, remap_target_from_fields
from .common import (
    PB_EVENT_CLASS_BY_TRANSCRIPT,
    PB_TSS_CHROM,
    PB_TSS_CORE_BP,
    PB_TSS_WINDOW_BP,
    TARGET_GENE,
    _require_columns,
)
from .long_read import prepare_ankrd30a_long_read_annotations


def _pb_tss_event_positions(*, force: bool = False) -> pd.DataFrame:
    """Return PB-supported TSS positions for the focused ANKRD30A TSS event."""
    # ReMap queries follow the four PB transcripts that define the Atera
    # luminal/invasive TSS event, not broader nearby TSS clusters.
    pacbio_tx, _, _ = prepare_ankrd30a_long_read_annotations(force=force)
    _require_columns(
        pacbio_tx,
        ["chrom", "strand", "tss_1based", "transcript_id"],
        "PacBio transcript table",
    )
    selected = pacbio_tx[
        pacbio_tx["transcript_id"].astype(str).isin(PB_EVENT_CLASS_BY_TRANSCRIPT)
    ].copy()
    if selected.empty:
        raise ValueError("No selected PB TSS positions found for ANKRD30A event")

    selected["event_class"] = selected["transcript_id"].map(PB_EVENT_CLASS_BY_TRANSCRIPT)
    selected["event_order"] = selected["transcript_id"].map(
        {tx: i for i, tx in enumerate(PB_EVENT_CLASS_BY_TRANSCRIPT)}
    )
    for column in (
        "tss_1based",
        "FL_counts",
        "FL_samples",
        "er_positive_fl_counts",
        "er_positive_fl_samples",
    ):
        if column in selected:
            selected[column] = pd.to_numeric(selected[column], errors="coerce")

    optional_sum_cols = [
        col
        for col in (
            "FL_counts",
            "FL_samples",
            "er_positive_fl_counts",
            "er_positive_fl_samples",
        )
        if col in selected
    ]
    tss = (
        selected.groupby(["chrom", "strand", "tss_1based"], as_index=False)
        .agg(
            source=("transcript_id", lambda _: "PacBio QC pass"),
            n_transcripts=("transcript_id", "nunique"),
            transcript_ids=("transcript_id", lambda x: "|".join(sorted(map(str, x)))),
            event_classes=("event_class", lambda x: "|".join(sorted(set(map(str, x))))),
            event_order=("event_order", "min"),
            **{f"{col}_sum": (col, "sum") for col in optional_sum_cols},
        )
        .sort_values(["event_order", "tss_1based"])
    )
    return tss.drop(columns=["event_order"])


def _supported_pb_tss_values(*, force: bool = False) -> list[int]:
    """Resolve PB-supported TSS positions used to window ReMap peaks."""
    tss = _pb_tss_event_positions(force=force)
    _require_columns(tss, ["tss_1based"], "PB-supported TSS table")
    values = pd.to_numeric(tss["tss_1based"], errors="coerce")
    values = values.dropna().astype(int).tolist()
    return values


def _min_abs_distance_to_tss(start: float, end: float, tss_values: list[int]) -> tuple[int, int]:
    """Return the nearest PB-supported TSS and peak-to-TSS distance in bp."""
    best_distance = np.inf
    best_tss = tss_values[0]
    for tss in tss_values:
        distance = 0 if start <= tss <= end else min(abs(start - tss), abs(end - tss))
        if distance < best_distance:
            best_distance = distance
            best_tss = tss
    return int(best_distance), int(best_tss)


def _summarize_pb_tss_remap_binding(*, force: bool = False) -> pd.DataFrame:
    """Summarize ReMap TF peaks near the PB-defined ANKRD30A TSS event in memory."""
    columns = [
        "tf",
        "tf_key",
        "remap_pb_tss_peak_count",
        "remap_pb_tss_core_peak_count",
        "remap_min_abs_distance_to_pb_tss_bp",
        "remap_nearest_pb_tss_1based",
        "remap_closest_peak",
        "remap_pb_tss_window_bp",
        "remap_pb_tss_core_bp",
    ]
    tss_values = _supported_pb_tss_values(force=force)
    if not REMAP_NR_HG38_BED.exists():
        raise FileNotFoundError(f"Missing ReMap hg38 BED: {project_path(REMAP_NR_HG38_BED)}")

    # Aggregate per TF, rather than per peak
    # Scan a single compact interval spanning the PB TSS cluster plus flanks.
    start = min(tss_values) - PB_TSS_WINDOW_BP
    end = max(tss_values) + PB_TSS_WINDOW_BP
    rows_by_tf: dict[str, dict[str, object]] = {}
    with open_text(REMAP_NR_HG38_BED) as handle:
        for line in handle:
            if not line.startswith(f"{PB_TSS_CHROM}\t"):
                continue
            fields = line.rstrip("\n").split("\t")
            if len(fields) < 4:
                continue
            peak_start = int(fields[1])
            peak_end = int(fields[2])
            if peak_end <= start or peak_start >= end:
                continue
            tf = remap_target_from_fields(fields)
            if not tf:
                continue
            distance, nearest_tss = _min_abs_distance_to_tss(peak_start, peak_end, tss_values)
            row = rows_by_tf.setdefault(
                tf,
                {
                    "tf": tf,
                    "tf_key": normalize_gene_symbol(tf),
                    "remap_pb_tss_peak_count": 0,
                    "remap_pb_tss_core_peak_count": 0,
                    "remap_min_abs_distance_to_pb_tss_bp": np.inf,
                    "remap_nearest_pb_tss_1based": np.nan,
                    "remap_closest_peak": "",
                    "remap_pb_tss_window_bp": PB_TSS_WINDOW_BP,
                    "remap_pb_tss_core_bp": PB_TSS_CORE_BP,
                },
            )
            row["remap_pb_tss_peak_count"] = int(row["remap_pb_tss_peak_count"]) + 1
            if distance <= PB_TSS_CORE_BP:
                row["remap_pb_tss_core_peak_count"] = int(row["remap_pb_tss_core_peak_count"]) + 1
            if distance < float(row["remap_min_abs_distance_to_pb_tss_bp"]):
                # Store one representative closest peak for labels/audits.
                row["remap_min_abs_distance_to_pb_tss_bp"] = int(distance)
                row["remap_nearest_pb_tss_1based"] = int(nearest_tss)
                row["remap_closest_peak"] = f"{PB_TSS_CHROM}:{peak_start}-{peak_end}:{fields[3]}"

    out = pd.DataFrame(rows_by_tf.values(), columns=columns)
    if out.empty:
        raise ValueError("ReMap hg38 BED produced no TF peaks near ANKRD30A PB TSSs")
    out["remap_min_abs_distance_to_pb_tss_bp"] = out["remap_min_abs_distance_to_pb_tss_bp"].replace(
        np.inf, np.nan
    )
    out = out.sort_values(["remap_min_abs_distance_to_pb_tss_bp", "tf"])
    return out


def ankrd30a_regulator_priority_table(
    du: pd.DataFrame,
    *,
    force: bool = False,
) -> pd.DataFrame:
    """Rank ANKRD30A DU regulators first by DU strength, then annotate binding support."""
    # Primary evidence: DU association for ANKRD30A across all configured
    # RBP/TF regulators. Binding evidence is appended after this ranking.
    _require_columns(
        du,
        [
            "gene",
            "covariate",
            "pvalue",
            "pvalue_adj",
            "statistic",
            "is_rbp",
            "is_tf_chip",
        ],
        "Atera DU result table",
    )
    work = du[du["gene"].astype(str).eq(TARGET_GENE)].copy()
    if work.empty:
        raise ValueError(f"Atera DU result table has no {TARGET_GENE} rows")
    work = work.sort_values(["pvalue_adj", "statistic"], ascending=[True, False]).reset_index(
        drop=True
    )
    work["ankrd30a_du_rank"] = np.arange(1, work.shape[0] + 1)
    work["regulator"] = work["covariate"].astype(str)
    work["regulator_key"] = work["regulator"].map(normalize_gene_symbol)
    work["regulator_class"] = np.select(
        [
            work["is_rbp"].astype(bool) & work["is_tf_chip"].astype(bool),
            work["is_tf_chip"].astype(bool),
            work["is_rbp"].astype(bool),
        ],
        ["RBP+TF", "TF", "RBP"],
        default="other",
    )

    # Binding evidence is deliberately not part of the primary sort key; it is
    # supporting evidence for the PB TSS event after the DU association.
    remap = _summarize_pb_tss_remap_binding(force=force)
    remap = remap.rename(columns={"tf_key": "regulator_key"}).drop(columns=["tf"], errors="ignore")
    work = work.merge(remap, on="regulator_key", how="left")
    for col in ["remap_pb_tss_peak_count", "remap_pb_tss_core_peak_count"]:
        values = work[col] if col in work else pd.Series(0, index=work.index)
        work[col] = pd.to_numeric(values, errors="coerce").fillna(0)
    work["has_pb_tss_remap_peak"] = work["remap_pb_tss_peak_count"].gt(0)
    work["has_pb_tss_core_remap_peak"] = work["remap_pb_tss_core_peak_count"].gt(0)

    work["binding_support_score"] = work["has_pb_tss_core_remap_peak"].astype(int) * 2 + work[
        "has_pb_tss_remap_peak"
    ].astype(int)
    # Final ordering remains DU-first; binding score only breaks ties/supports labels.
    work = work.sort_values(
        ["ankrd30a_du_rank", "binding_support_score", "regulator"],
        ascending=[True, False, True],
    )
    return work


def _append_unique_regulators(selected: list[str], regulators: Iterable[str]) -> list[str]:
    """Append regulator symbols while preserving the first observed order."""
    seen = {normalize_gene_symbol(regulator) for regulator in selected}
    for regulator in regulators:
        key = normalize_gene_symbol(str(regulator))
        if not key or key in seen:
            continue
        selected.append(str(regulator))
        seen.add(key)
    return selected


def select_ankrd30a_focus_regulators(priority: pd.DataFrame, *, top_n_each: int = 5) -> list[str]:
    """Select the compact TF set used by the DU/TCGA figure.

    The figure shows two groups: de novo DU TFs without PB-TSS ReMap support and
    DU-ranked TFs with PB-TSS ReMap support. Keeping this selection here limits
    TCGA expression loading and correlation output to the plotted regulators.
    """
    if priority.empty:
        raise ValueError("ANKRD30A regulator-priority table is empty")
    _require_columns(
        priority,
        [
            "regulator",
            "regulator_class",
            "ankrd30a_du_rank",
            "pvalue",
            "pvalue_adj",
            "has_pb_tss_remap_peak",
            "remap_pb_tss_core_peak_count",
            "remap_pb_tss_peak_count",
            "remap_min_abs_distance_to_pb_tss_bp",
        ],
        "ANKRD30A regulator-priority table",
    )
    tf_priority = priority[priority["regulator_class"].isin(["TF", "RBP+TF"])].copy()
    if tf_priority.empty:
        raise ValueError("ANKRD30A regulator-priority table has no TF regulators")
    has_binding = tf_priority["has_pb_tss_remap_peak"].astype(bool)

    # Top N DU-ranked TFs without PB TSS ReMap support
    de_novo = (
        tf_priority[~has_binding]
        .sort_values(["ankrd30a_du_rank", "regulator"], ascending=[True, True])
        .head(top_n_each)["regulator"]
        .astype(str)
        .tolist()
    )
    # Top N DU-ranked TFs with PB TSS ReMap support
    binding = tf_priority[has_binding].copy()

    if not de_novo:
        raise ValueError("ANKRD30A regulator-priority table has no de novo DU TFs")
    if binding.empty:
        raise ValueError("ANKRD30A regulator-priority table has no PB-TSS-binding TFs")
    binding["pvalue"] = pd.to_numeric(binding["pvalue"], errors="coerce")
    binding["pvalue_adj"] = pd.to_numeric(binding["pvalue_adj"], errors="coerce")
    binding["remap_pb_tss_core_peak_count"] = pd.to_numeric(
        binding["remap_pb_tss_core_peak_count"], errors="coerce"
    ).fillna(0)
    binding["remap_pb_tss_peak_count"] = pd.to_numeric(
        binding["remap_pb_tss_peak_count"], errors="coerce"
    ).fillna(0)
    binding["remap_min_abs_distance_to_pb_tss_bp"] = pd.to_numeric(
        binding["remap_min_abs_distance_to_pb_tss_bp"], errors="coerce"
    )
    # Among TFs with TSS binding support, choose by DU p-value first; peak count
    # and distance only resolve similarly associated regulators.
    binding = binding.sort_values(
        [
            "pvalue",
            "pvalue_adj",
            "ankrd30a_du_rank",
            "remap_pb_tss_core_peak_count",
            "remap_pb_tss_peak_count",
            "remap_min_abs_distance_to_pb_tss_bp",
            "regulator",
        ],
        ascending=[True, True, True, False, False, True, True],
    )
    return _append_unique_regulators(de_novo, binding.head(top_n_each)["regulator"].astype(str))
